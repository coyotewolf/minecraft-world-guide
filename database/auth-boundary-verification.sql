begin;
create temporary table audit_fixture as select gen_random_uuid() player,gen_random_uuid() pending,gen_random_uuid() admin,gen_random_uuid() sp,gen_random_uuid() sn,gen_random_uuid() sa;
insert into auth.users(id) select player from audit_fixture union all select pending from audit_fixture union all select admin from audit_fixture;
insert into public.profiles(id,game_id) select player,'AuditPlayer' from audit_fixture union all select pending,'AuditPending' from audit_fixture union all select admin,'AuditAdmin' from audit_fixture;
insert into private.accounts(user_id,game_key,recovery_hash,approved) select id,id::text,'audit-only',id<>(select pending from audit_fixture) from public.profiles where id in(select player from audit_fixture union all select pending from audit_fixture union all select admin from audit_fixture);
insert into auth.sessions(id,user_id) select sp,player from audit_fixture union all select sn,pending from audit_fixture union all select sa,admin from audit_fixture;
insert into private.admins(user_id) select admin from audit_fixture;
grant select on audit_fixture to authenticated;
set local role authenticated;
do $$
declare f record; blocked boolean;
begin
select * into f from audit_fixture;
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.player,'session_id',f.sp,'role','authenticated','aal','aal2','user_metadata',jsonb_build_object('admin',true,'approved',true))::text,true);
assert private.valid_session(),'approved player must work';
assert not private.is_admin(),'metadata cannot grant admin';
blocked:=false;begin perform public.admin_make(f.player);exception when others then if sqlerrm='需要管理員權限' then blocked:=true;else raise;end if;end;assert blocked,'player cannot promote self';
blocked:=false;begin perform public.admin_approve(f.pending,true);exception when others then if sqlerrm='需要管理員權限' then blocked:=true;else raise;end if;end;assert blocked,'player cannot approve someone';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.pending,'session_id',f.sn,'role','authenticated','aal','aal2','user_metadata',jsonb_build_object('approved',true,'admin',true))::text,true);
assert not private.valid_session(),'pending metadata cannot bypass approval';
assert not private.is_admin(),'pending cannot become admin';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.admin,'session_id',f.sp,'role','authenticated','aal','aal2')::text,true);
assert not private.valid_session(),'session must belong to uid';
assert not private.is_admin(),'other session cannot impersonate admin';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.admin,'session_id',f.sa,'role','authenticated','aal','aal1')::text,true);
assert not private.is_admin(),'admin requires MFA';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.admin,'session_id',f.sa,'role','authenticated','aal','aal2')::text,true);
assert private.is_admin(),'legitimate admin preserved';
perform public.admin_approve(f.pending,true);
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.pending,'session_id',f.sn,'role','authenticated','aal','aal1')::text,true);
assert private.valid_session(),'admin can approve pending player';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.admin,'session_id',f.sa,'role','authenticated','aal','aal2')::text,true);
perform public.admin_approve(f.pending,false);
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.pending,'session_id',f.sn,'role','authenticated','aal','aal2')::text,true);
assert not private.valid_session(),'revoked session denied';
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.admin,'session_id',f.sa,'role','authenticated','aal','aal2')::text,true);
perform public.admin_make(f.player);
perform set_config('request.jwt.claims',jsonb_build_object('sub',f.player,'session_id',f.sp,'role','authenticated','aal','aal2')::text,true);
assert private.is_admin(),'admin can delegate admin';
end $$;
reset role;
select 'PASS: approval, metadata forgery, session binding, MFA, revocation and legitimate admin actions; rollback all fixtures' as result;
rollback;
